def test_the_committed_reading_says_which_build_took_it():
    """Backfilled from git, not guessed: commit cbbd421 added this file and
    its subject is "v0.24.0 — … the perf lane is CALIBRATED"."""
    calibration = yaml.safe_load(COMMITTED.read_text())["calibration"]
    assert str(calibration["avs_version"]) == "0.24.0"
    assert calibration["at"] == "2026-07-26"
