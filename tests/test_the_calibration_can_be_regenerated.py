def test_the_status_names_the_build_and_flags_a_stale_one(tmp_path, monkeypatch):
    from ai_venture_studio import __version__

    target = tmp_path / "cal.yaml"
    monkeypatch.setattr(calibrate_perf, "CALIBRATION_FILE", target)
    target.write_text(yaml.safe_dump({"calibration": {
        **_result().model_dump(), "at": "2026-07-26", "avs_version": "0.24.0"}}))
    status = calibrate_perf.lane_status()
    assert "v0.24.0" in status, "the reading does not say which build took it"
    assert f"current build v{__version__}" in status, (
        "a reading from another build reads exactly like a current one"
    )


def test_a_current_reading_does_not_nag(tmp_path, monkeypatch):
    from ai_venture_studio import __version__

    target = tmp_path / "cal.yaml"
    monkeypatch.setattr(calibrate_perf, "CALIBRATION_FILE", target)
    target.write_text(yaml.safe_dump({"calibration": {
        **_result().model_dump(), "at": "2026-08-22",
        "avs_version": __version__}}))
    status = calibrate_perf.lane_status()
    assert f"v{__version__}" in status and "current build" not in status


def test_an_unstamped_reading_says_unrecorded_and_never_current(tmp_path, monkeypatch):
    """ADR-056's rule: absent must not resolve toward the reassuring answer.
    A file with no build key is one this code has never written; reading it as
    current would turn the oldest possible artifact into a fresh one."""
    target = tmp_path / "cal.yaml"
    monkeypatch.setattr(calibrate_perf, "CALIBRATION_FILE", target)
    target.write_text(yaml.safe_dump({"calibration": {
        **_result().model_dump(), "at": "2026-07-26"}}))
    status = calibrate_perf.lane_status()
    assert "unrecorded build" in status and "current build" in status


def test_a_stale_build_is_described_and_never_downgraded(tmp_path, monkeypatch):
    """Staleness is not a verdict. Nothing here knows whether the lane's
    behaviour moved between two builds, so demoting a real reading to
    PROVISIONAL on a version bump would be a guess wearing a verdict's
    clothes — and it would make `avs perf-calibrate` mandatory on every
    release for a lane nobody changed."""
    target = tmp_path / "cal.yaml"
    monkeypatch.setattr(calibrate_perf, "CALIBRATION_FILE", target)
    target.write_text(yaml.safe_dump({"calibration": {
        **_result().model_dump(), "at": "2020-01-01", "avs_version": "0.0.1"}}))
    assert calibrate_perf.lane_status().startswith("CALIBRATED")


def test_a_failed_calibration_is_still_provisional(tmp_path, monkeypatch):
    """The build stamp is additive. The 80% catch-rate bar that decides
    CALIBRATED vs PROVISIONAL is untouched by this change."""
    target = tmp_path / "cal.yaml"
    monkeypatch.setattr(calibrate_perf, "CALIBRATION_FILE", target)
    target.write_text(yaml.safe_dump({"calibration": {
        **_result(catch_rate=0.6).model_dump(), "at": "2026-08-22",
        "avs_version": "0.114.0"}}))
    assert calibrate_perf.lane_status() == "PROVISIONAL"


